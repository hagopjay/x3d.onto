#!/usr/bin/env python3
"""Sketch of Option B: additive owl:Restriction axioms (allValuesFrom the field's acceptableNodeTypes) per concrete parent class, generated from X3DUOM,
loaded next to the unchanged 4.1 Turtle, and queried back. Checks that the encoding is lossless w.r.t. X3DUOM and syntactically valid Turtle.
It is a SKETCH: no reasoner or Protege was run, and nothing here changes the Consortium's files.
usage: proposal_sketch.py <x3d_mcp checkout> -> proposal/X3dOntology4.1.narrowing-sketch.ttl, proposal/narrowed_node_parents.rq, out/proposal_check.json"""
import json, sys, time
from pathlib import Path
import rdflib
from rdflib import RDF, RDFS, OWL
root = Path(sys.argv[1]).expanduser(); sys.path.insert(0, str(root / "src"))
from x3d_utils.x3duom import get_x3duom
HERE = Path(__file__).resolve().parent.parent
NS = "https://www.web3d.org/specifications/X3dOntology4.1#"
base = rdflib.Graph(); base.parse(str(HERE / "data" / "X3dOntology4.1.ttl"), format="turtle")
U = get_x3duom().get_concrete_nodes(); KEEP = ("initializeOnly", "inputOutput")
up = lambda s: s[:1].upper() + s[1:]
lines = [f"""# SKETCH for discussion. NOT part of any Web3D file. Generated by harness/proposal_sketch.py from X3DUOM 4.1 acceptableNodeTypes.
# Additive: loaded next to the unchanged X3dOntology4.1.ttl. Not run through a reasoner or Protege.
@prefix : <{NS}> .
@prefix owl: <http://www.w3.org/2002/07/owl#> .
@prefix rdfs: <http://www.w3.org/2000/01/rdf-schema#> .
"""]
n_ax = 0; unresolved = []
for p, d in sorted(U.items()):
    for f in d["fields"]:
        a = f.get("acceptableNodeTypes")
        if not a or f["type"] not in ("SFNode", "MFNode") or f["accessType"] not in KEEP or f["name"] in ("IS", "metadata"): continue
        prop = "has" + up(f["name"]); types = a.split("|")
        miss = [t for t in types + [p, prop] if (rdflib.URIRef(NS + t), None, None) not in base and (None, None, rdflib.URIRef(NS + t)) not in base]
        if miss: unresolved.append((p, f["name"], miss[:3])); continue
        rng = f" ( {' '.join(':' + t for t in types)} ) " if len(types) > 1 else None
        body = f"[ a owl:Class ; owl:unionOf{rng}]" if rng else f":{types[0]}"
        lines.append(f":{p} rdfs:subClassOf [ a owl:Restriction ; owl:onProperty :{prop} ; owl:allValuesFrom {body} ] .")
        n_ax += 1
ttl = "\n".join(lines) + "\n"; out = HERE / "proposal" / "X3dOntology4.1.narrowing-sketch.ttl"; out.write_text(ttl)
sk = rdflib.Graph(); sk.parse(str(out), format="turtle")
Q = f"""PREFIX : <{NS}>
PREFIX owl: <http://www.w3.org/2002/07/owl#>
PREFIX rdfs: <http://www.w3.org/2000/01/rdf-schema#>
PREFIX rdf: <http://www.w3.org/1999/02/22-rdf-syntax-ns#>
# which classes may a given class sit under, per the per-parent restrictions (child ranges expanded through rdfs:subClassOf*)
SELECT DISTINCT ?parent ?prop ?child WHERE {{
  ?parent rdfs:subClassOf [ a owl:Restriction ; owl:onProperty ?prop ; owl:allValuesFrom ?r ] .
  ?r (owl:unionOf/rdf:rest*/rdf:first)? ?range .
  ?child rdfs:subClassOf* ?range .
}}"""
(HERE / "proposal" / "narrowed_node_parents.rq").write_text(Q + "\n")
g = base + sk; t0 = time.time(); rows = {(str(a)[len(NS):], str(b)[len(NS):], str(c)[len(NS):]) for a, b, c in g.query(Q)}
ms = round((time.time() - t0) * 1000)
conc = lambda x: x in U
pairs = {(c, p, pr[3:4].lower() + pr[4:]) for p, pr, c in ((a, b, c) for a, b, c in rows) if conc(c) and conc(p)}
uv = json.loads((HERE / "data" / "uom_universe.json").read_text())
# universe keys: rebuild from the same rule used in uom_universe.py
M = json.loads((HERE / "data" / "explorer.json").read_text()); N = {n["id"]: n for n in M["nodes"]}
uni = set()
for p, d in U.items():
    for f in d["fields"]:
        a = f.get("acceptableNodeTypes")
        if not a or f["name"] in ("IS", "metadata") or f["type"] not in ("SFNode", "MFNode") or f["accessType"] not in KEEP: continue
        r = set(a.split("|"))
        for c in U:
            if ({c} | set(N[c]["ancs"])) & r: uni.add((c, p, f["name"]))
res = dict(axioms=n_ax, sketch_triples=len(sk), unresolved_terms=unresolved[:10], unresolved_count=len(unresolved), query_ms=ms, query_rows=len(rows), concrete_pairs=len(pairs),
           universe_pairs=len(uni), identical_to_universe=pairs == uni, only_in_query=len(pairs - uni), only_in_universe=len(uni - pairs))
(HERE / "out" / "proposal_check.json").write_text(json.dumps(res, indent=1)); print(json.dumps(res))
