#!/usr/bin/env python3
"""Compose RESULTS.md from the finished runs: per domain, the arm table, paired tests, completeness, judge agreement, cost, latency. Mechanical only; the narrative is written separately.
usage: final_report.py (x3d_mcp venv python)"""
import collections, io, json, statistics, sys, contextlib, importlib.util
from pathlib import Path
HERE = Path(__file__).resolve().parent; runs = HERE / "runs"
sys.argv = [sys.argv[0]]
spec = importlib.util.spec_from_file_location("runner", HERE / "runner.py"); R = importlib.util.module_from_spec(spec); spec.loader.exec_module(R)
L = ["# Results: model-driven evaluation of the validator loops (gemini-3.8-flash)", "", "Generated by `final_report.py` from `runs/`. Gate = strict validity. See PLAN.md for design and threats; numbers here are for this model and these prompts only.", ""]
for dom in ("x3d", "urdf", "gltf"):
    f = runs / f"{dom}-gemini-3.8-flash.jsonl"
    if not f.exists(): L += [f"## {dom}", "not finished.", ""]; continue
    buf = io.StringIO()
    with contextlib.redirect_stdout(buf): R.report(f)
    raw = [json.loads(l) for l in (runs / f"raw-{dom}-gemini-3.8-flash.jsonl").read_text().splitlines()]
    sec = [r["seconds"] for r in raw if "seconds" in r]
    L += [f"## {dom}", "```", buf.getvalue().rstrip(), "```", f"- {len(raw)} paid answers, estimated ${sum(r['est_usd'] for r in raw):.2f}; latency median {statistics.median(sec):.0f}s, p90 {sorted(sec)[int(.9 * len(sec))]:.0f}s, max {max(sec):.0f}s." if sec else ""]
    jf = runs / f"judge-{dom}-gemini-3.8-flash.jsonl"
    if jf.exists():
        J = [json.loads(l) for l in jf.read_text().splitlines()]; ok = [j for j in J if j["score"] is not None]
        by = collections.defaultdict(list)
        for j in ok: by[j["arm"]].append(j["score"])
        L += [f"- Gemini judge on valid documents ({len(ok)} judged): " + "; ".join(f"{a}: mean {sum(v) / len(v):.2f}/2, fully {sum(1 for x in v if x == 2)}/{len(v)}" for a, v in sorted(by.items())),
              f"- judge vs mechanical count check: agree on {sum(1 for j in ok if (j['score'] == 2) == bool(j['mech_complete']))}/{len(ok)} documents"]
    L.append("")
(HERE / "RESULTS.md").write_text("\n".join(L)); print("RESULTS.md written", len(L), "lines")
